def _flat(bg: str, r: int, g: int, b: int, a: float) -> str:
    """Composite translucent RGB over solid bg hex → solid hex."""
    bg = bg.lstrip("#")
    br, bg_, bb = int(bg[0:2], 16), int(bg[2:4], 16), int(bg[4:6], 16)
    a = max(0.0, min(1.0, a))
    rr = int(br * (1 - a) + r * a)
    gg = int(bg_ * (1 - a) + g * a)
    bb2 = int(bb * (1 - a) + b * a)
    return f"#{rr:02x}{gg:02x}{bb2:02x}"


def _muted(text: str, alpha: float = 0.55) -> str:
    t = text.lstrip("#")
    r, g, b = int(t[0:2], 16), int(t[2:4], 16), int(t[4:6], 16)
    # blend toward black for "muted" solid
    return _flat("#000000", r, g, b, alpha)


