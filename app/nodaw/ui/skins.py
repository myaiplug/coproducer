def _merge_design(skin: dict[str, Any]) -> dict[str, Any]:
    out = dict(skin)
    design = dict(_DESIGN_BASE)
    design.update(_DESIGN_OVERRIDES.get(skin.get("id", ""), {}))
    out.update(design)
    return out


# Attach design tokens to every skin (colors stay skin-specific)
for _sid in list(SKINS.keys()):
    SKINS[_sid] = _merge_design(SKINS[_sid])


def get_skin(skin_id: str | None) -> dict[str, Any]:
    if skin_id and skin_id in SKINS:
        return SKINS[skin_id]
    return SKINS[DEFAULT_SKIN]


def list_skins() -> list[dict[str, Any]]:
    return [SKINS[k] for k in SKIN_ORDER if k in SKINS]

